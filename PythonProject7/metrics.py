import numpy as np


def accuracy_score(y_true, y_pred):
    return np.mean(y_true == y_pred) #np.mean считает среднее арифметическое
    # этих 1 и 0 — то есть долю правильных ответов.

#Precision – из всех, кого модель назвала классом 1,
# какая доля действительно 1. Характеризует «точность попадания».
# Если модель редко ошибается, называя 0 единицей, precision высокая.
def precision_score(y_true, y_pred):
    tp = np.sum((y_true == 1) & (y_pred == 1))
    fp = np.sum((y_true == 0) & (y_pred == 1))
    return tp / (tp + fp) if (tp + fp) > 0 else 0.0

#Recall – из всех настоящих 1 какую долю модель нашла.
# Если модель пропускает мало единиц, recall высокий.
def recall_score(y_true, y_pred):
    tp = np.sum((y_true == 1) & (y_pred == 1))
    fn = np.sum((y_true == 1) & (y_pred == 0))
    return tp / (tp + fn) if (tp + fn) > 0 else 0.0


def f1_score(y_true, y_pred): #Среднее гармоническое precision и recall. Оно высокое, только если
    # и precision, и recall высокие.
    # Если одно из них маленькое, F1 тоже будет низким.
    p = precision_score(y_true, y_pred)
    r = recall_score(y_true, y_pred)
    return 2 * (p * r) / (p + r) if (p + r) > 0 else 0.0

#ROC-кривая — это график, который получается, если пройтись по всем возможным порогам
# от 0 до 1 и для каждого посчитать две величины:
#TPR (True Positive Rate) = Recall = доля найденных реальных единиц.
#FPR (False Positive Rate) = доля реальных нулей, которых модель ошибочно назвала единицами.
#AUC (Area Under Curve) — площадь под этой кривой.
# Если AUC=1, модель идеально разделяет классы. AUC=0.5 — бесполезная модель.

#y_probs — это массив вероятностей, которые выдала модель (например: [0.2, 0.9, 0.6]).

#np.argsort(...) — эта функция не сортирует сами числа. Она возвращает номера мест (индексы), как если бы числа были отсортированы.

#[::-1] — по умолчанию сортировка идет по возрастанию.
# Эта штука разворачивает список задом наперед, чтобы в начале
    # шли самые высокие вероятности (самые уверенные предсказания).

#y_true_sorted = y_true[desc_score_indices] — мы берем реальные ответы (нули и единицы)
    # и перемешиваем их в том же порядке, в каком выстроились вероятности.

def roc_auc_score(y_true, y_probs):
    # Простая реализация вычисления площади под кривой ROC
    desc_score_indices = np.argsort(y_probs, kind="mergesort")[::-1]
    y_true_sorted = y_true[desc_score_indices]

    # Мы идем по нашей отсортированной очереди сверху вниз (от самых уверенных к менее уверенным) и считаем.

    # np.cumsum (cumulative sum) — это кумулятивная (накапливающаяся) сумма.
    # Она бежит по массиву и на каждом шаге прибавляет текущее число к сумме предыдущих.

    # tps (True Positives, Верные срабатывания) — поскольку единицы в массиве y_true_sorted — это правильные ответы класса 1,
    # кумулятивная сумма просто считает: «Ага, встретили первую единицу, счет 1.
    # Встретили вторую — счет 2. Встретили ноль — счет остался 2».

    # fps (False Positives, Ложные срабатывания) — конструкция 1 - y_true_sorted превращает все нули в единицы, а единицы в нули.
    # Теперь cumsum считает наши ошибки. Каждый раз, когда в топе рейтинга (где должны быть единицы) попадается ноль
    # счетчик ложных срабатываний fps увеличивается.

    tps = np.cumsum(y_true_sorted)
    fps = np.cumsum(1 - y_true_sorted)

    #TPR (True Positive Rate) — процент найденных единиц на каждом шаге.
    #FPR (False Positive Rate) — процент допущенных ошибок.

    tpr = tps / tps[-1]
    fpr = fps / fps[-1]

    #Массивы tpr и fpr — это координаты X и Y для графика (той самой ROC-кривой).
    #np.trapezoid(tpr, fpr) — берет эти координаты и с помощью математического метода
    # трапеций вычисляет площадь под этим графиком.
    #Итог: Эта площадь и есть наш ROC-AUC score.

    return np.trapezoid(tpr, fpr), fpr, tpr